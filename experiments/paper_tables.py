"""Write the paper's tables and figures from the stored results (no number typed by hand).

Reads ``results/benchmark/<tag>/results.csv`` (dataset means as in ``experiments/analyze.py``),
``results/timing/<timing-tag>/summary.csv`` (``experiments/timing.py``),
``results/memory/<memory-tag>/memory.csv`` (``experiments/memory.py``) and the CD diagrams
in ``results/benchmark/<tag>/secondary/`` (``experiments/secondary.py``).

Writes ``paper/tables/{primary,subsets,timing,memory,wilcoxon,metrics,published,
ablations,operations}.tex`` and copies the CD diagrams
(PDF) to ``paper/figures/``. The outputs are committed, so the paper builds without the
data.

Usage:
    uv run python experiments/secondary.py all --tag m2 --timing-tag endpoint
    uv run python experiments/paper_tables.py --tag m2 --timing-tag endpoint --memory-tag endpoint
"""

from __future__ import annotations

import argparse
import csv
import shutil
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from analyze import RESULTS_ROOT, THRESHOLD, dataset_means, read, subset
from hanner_hydra.stats import bayesian_signed_rank

ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT / "paper"
CANDIDATE = "hanner"
ARMS = ["hydra", "control_sym", "control"]
LABEL = {
    "hanner": "Hanner-Hydra",
    "hydra": "Hydra",
    "control_sym": r"\texttt{control\_sym}",
    "control": r"\texttt{control}",
}
HEADER = "% Generated by experiments/paper_tables.py; do not edit by hand.\n"


def read_means(bench: Path, name: str | None = None) -> dict[str, np.ndarray]:
    """Unrounded dataset means as ``analyze.py`` computes them (its CSV is rounded, which
    turns near-ties into ties in the W/T/L counts)."""
    acc = read(bench / "results.csv")
    if name:
        keep = subset(name)
        acc = {a: {k: v for k, v in d.items() if k[0] in keep} for a, d in acc.items()}
    return dataset_means(acc, [CANDIDATE, *ARMS], None)[1]


def comparison(a: np.ndarray, b: np.ndarray) -> dict:
    d = a - b
    res = bayesian_signed_rank(a, b, rope=0.5)
    return {
        "a": a.mean(),
        "b": b.mean(),
        "delta": d.mean(),
        "wtl": f"{(d > 0).sum()}/{(d == 0).sum()}/{(d < 0).sum()}",
        "p": res.p_not_worse,
        "lrr": f"{res.p_left:.3f} / {res.p_rope:.3f} / {res.p_right:.3f}",
    }


def write(name: str, body: str) -> None:
    out = PAPER / "tables" / f"{name}.tex"
    out.parent.mkdir(exist_ok=True)
    out.write_text(HEADER + body)
    print(f"-> {out.relative_to(ROOT)}")


def primary(bench: Path) -> None:
    m = read_means(bench)
    lines = [
        r"\begin{tabular}{lrrlcc}",
        r"\toprule",
        r"Comparison & Means (\%) & $\Delta$ & W/T/L & $P$(left / rope / right)"
        r" & $P$(not worse) \\",
        r"\midrule",
    ]
    for arm in ARMS:
        c = comparison(m[CANDIDATE], m[arm])
        p = f"\\textbf{{{c['p']:.3f}}}" if c["p"] >= THRESHOLD else f"{c['p']:.3f}"
        lines.append(
            f"vs {LABEL[arm]} & {c['a']:.2f} vs {c['b']:.2f} & ${c['delta']:+.2f}$ & "
            f"{c['wtl']} & {c['lrr']} & {p} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    write("primary", "\n".join(lines))


def subsets(bench: Path) -> None:
    lines = [
        r"\begin{tabular}{lrrrrr}",
        r"\toprule",
        r"Subset & Datasets & $\Delta$ vs Hydra & $P$(not worse) & $\Delta$ vs "
        r"\texttt{control\_sym} & $P$(not worse) \\",
        r"\midrule",
    ]
    for name, label in [(None, "All"), ("ucr112", "UCR"), ("uea26", "UEA"), ("fresh", "Fresh")]:
        m = read_means(bench, name)
        h, s = comparison(m[CANDIDATE], m["hydra"]), comparison(m[CANDIDATE], m["control_sym"])
        lines.append(
            f"{label} & {len(m[CANDIDATE])} & ${h['delta']:+.2f}$ & {h['p']:.3f} & "
            f"${s['delta']:+.2f}$ & {s['p']:.3f} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    write("subsets", "\n".join(lines))


def timing(path: Path) -> None:
    with path.open() as f:
        rows = list(csv.DictReader(f))
    t = {k: np.array([float(r[k]) for r in rows]) for k in ("hydra_s", "hanner_s", "control_sym_s")}
    r_hydra = t["hydra_s"] / t["hanner_s"]
    r_sym = t["control_sym_s"] / t["hanner_s"]
    lines = [
        r"\begin{tabular}{lr}",
        r"\toprule",
        r"Quantity (median over datasets) & Value \\",
        r"\midrule",
        f"Hydra / Hanner-Hydra transform time & {np.median(r_hydra):.2f}$\\times$ \\\\",
        f"\\texttt{{control\\_sym}} / Hanner-Hydra & {np.median(r_sym):.2f}$\\times$ \\\\",
        f"Hydra / \\texttt{{control\\_sym}} & {np.median(t['hydra_s'] / t['control_sym_s']):.2f}"
        r"$\times$ \\",
        f"Smallest Hydra / Hanner-Hydra ratio & {r_hydra.min():.2f}$\\times$ \\\\",
        f"Datasets & {len(rows)} \\\\",
        r"\bottomrule",
        r"\end{tabular}",
        "",
    ]
    write("timing", "\n".join(lines))


def memory(path: Path) -> None:
    with path.open() as f:
        rows = list(csv.DictReader(f))
    extra = {(r["dataset"], r["arm"]): float(r["extra_mb"]) for r in rows}
    names = sorted({d for d, a in extra if a == CANDIDATE and (d, "hydra") in extra})
    arms = sorted({a for _, a in extra}, key=lambda a: (a != CANDIDATE, a))
    lines = [
        r"\begin{tabular}{lr}",
        r"\toprule",
        r"Arm & Median extra peak memory (MB) \\",
        r"\midrule",
    ]
    for a in arms:
        vals = [extra[n, a] for n in names if (n, a) in extra]
        lines.append(f"{LABEL.get(a, a)} & {np.median(vals):.0f} \\\\")
    ratio = np.median([extra[n, "hydra"] / extra[n, CANDIDATE] for n in names])
    lines += [
        r"\midrule",
        f"Hydra / Hanner-Hydra (median of per-dataset ratios) & {ratio:.1f}$\\times$ \\\\",
        r"\bottomrule",
        r"\end{tabular}",
        "",
    ]
    write("memory", "\n".join(lines))


def read_secondary(bench: Path, name: str) -> list[dict]:
    """A CSV written by ``experiments/secondary.py`` (unrounded values)."""
    with (bench / "secondary" / f"{name}.csv").open() as f:
        return list(csv.DictReader(f))


def label(arm: str) -> str:
    if arm.startswith(f"{CANDIDATE}:"):
        key, _, value = arm.partition(":")[2].partition("=")
        return rf"\texttt{{{key.replace('_', chr(92) + '_')}={value}}}"
    return LABEL.get(arm, arm)


def bold_p(p: float) -> str:
    """A probability, in bold when it meets the decision threshold."""
    return rf"\textbf{{{p:.3f}}}" if p >= THRESHOLD else f"{p:.3f}"


def wtl(r: dict) -> str:
    return f"{r['wins']}/{r['ties']}/{r['losses']}"


def wilcoxon(bench: Path) -> None:
    lines = [
        r"\begin{tabular}{llrlrr}",
        r"\toprule",
        r"Pair & & $\Delta$ & W/T/L & $p$ & $p$ (Holm) \\",
        r"\midrule",
    ]
    for r in read_secondary(bench, "wilcoxon_all"):
        lines.append(
            f"{label(r['a'])} & vs {label(r['b'])} & ${float(r['mean_diff']):+.2f}$ & {wtl(r)} & "
            f"{float(r['p']):.3f} & {float(r['p_holm']):.3f} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    write("wilcoxon", "\n".join(lines))


def metrics(bench: Path) -> None:
    rows = {(r["metric"], r["subset"], r["vs"]): r for r in read_secondary(bench, "metrics_bayes")}
    names = [
        ("accuracy", "Accuracy"),
        ("balanced_accuracy", "Balanced accuracy"),
        ("f1_macro", "Macro-F1"),
    ]
    lines = [
        r"\begin{tabular}{llrrrr}",
        r"\toprule",
        r"Metric & Datasets & $\Delta$ vs Hydra & $P$(not worse) & $\Delta$ vs "
        r"\texttt{control\_sym} & $P$(not worse) \\",
        r"\midrule",
    ]
    for group, group_label in [("all", "All (138)"), ("uea26", "UEA (26)")]:
        for key, name in names:
            h, s = rows[key, group, "hydra"], rows[key, group, "control_sym"]
            lines.append(
                f"{name} & {group_label} & ${float(h['diff']):+.2f}$ & "
                f"{bold_p(float(h['p_not_worse']))} & ${float(s['diff']):+.2f}$ & "
                f"{bold_p(float(s['p_not_worse']))} \\\\"
            )
        if group == "all":
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    write("metrics", "\n".join(lines))


def published(bench: Path) -> None:
    names = {
        "WEASEL-2.0": "WEASEL 2.0",
        "MiniROCKET": "MiniRocket",
        "MultiROCKET": "MultiRocket",
        "HC2": "HIVE-COTE 2.0",
    }
    lines = [
        r"\begin{tabular}{lrrlcl}",
        r"\toprule",
        r"Hanner-Hydra vs & Means (\%) & $\Delta$ & W/T/L & $P$(left / rope / right) & Label \\",
        r"\midrule",
    ]
    for r in read_secondary(bench, "published_bayes"):
        lrr = " / ".join(f"{float(r[k]):.3f}" for k in ("p_left", "p_rope", "p_right"))
        lines.append(
            f"{names.get(r['vs'], r['vs'])} & {float(r['hanner_mean']):.2f} vs "
            f"{float(r['other_mean']):.2f} & ${float(r['diff']):+.2f}$ & {wtl(r)} & {lrr} & "
            f"{r['verdict']} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    write("published", "\n".join(lines))


def ablations(bench: Path) -> None:
    rows = read_secondary(bench, "ablations")
    by = {(r["arm"], r["vs"]): r for r in rows}
    lines = [
        r"\begin{tabular}{lrrrlrr}",
        r"\toprule",
        r"Variant & Datasets & Mean (\%) & $\Delta$ vs default & W/T/L & $P$(rope) "
        r"& $\Delta$ vs Hydra \\",
        r"\midrule",
    ]
    for arm in dict.fromkeys(r["arm"] for r in rows):
        d, h = by[arm, CANDIDATE], by[arm, "hydra"]
        lines.append(
            f"{label(arm)} & {d['n']} & {float(d['arm_mean']):.2f} & "
            f"${float(d['diff']):+.2f}$ & {wtl(d)} & "
            f"{float(d['p_rope']):.3f} & ${float(h['diff']):+.2f}$ \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    write("ablations", "\n".join(lines))


def operations(n_blocks: int = 2000, seed: int = 0) -> None:
    """Arithmetic per time step of one (dilation, input) block, from the frozen sampler.

    Cost model (per position, on the channel-summed input):
    * Hanner group: l absolute values (each with its sign test), then l - 1 additions or
      comparisons (the winner recursion in the paper).
    * Matched ternary group (``control`` / ``control_sym``) as timed: ``ternary_block`` in
      ``_numba.py`` evaluates every vertex as a dense dot product over all l taps, i.e.
      l multiplications by -1, 0 or 1 and l - 1 additions per vertex, then |V| - 1
      comparisons.
    * The same group evaluated sparsely (not implemented): nnz(v) - 1 additions or
      subtractions per vertex, then |V| - 1 comparisons.
    * Hydra group (k Gaussian kernels): k * (l multiplications + l - 1 additions), then
      2 (k - 1) comparisons (Hydra finds the maximum and the minimum).
    Groups are drawn until the block's atom budget is reached, as in ``fit``. Needs no data.
    """
    from hanner_hydra import HannerHydraTransform
    from hanner_hydra.cotree import sample_cotree

    p = HannerHydraTransform().get_params()  # the frozen defaults
    length, budget = p["kernel_length"], p["atom_budget"]
    hydra_k = 8  # aeon HydraClassifier(n_kernels=8); 256 / 8 = 32 groups per block
    rng = np.random.default_rng(seed)
    sizes, hanner_ops, matched_ops, dense_ops, groups = [], [], [], [], []
    for _ in range(n_blocks):
        atoms = h_ops = m_ops = d_ops = n = 0
        while atoms < budget:
            tree = sample_cotree(length, rng, p["max_vertices"], p["p_product"], p["contiguous"])
            nnz = np.count_nonzero(tree.vertices(), axis=1)
            sizes.append(tree.size)
            atoms += tree.size
            h_ops += 2 * length - 1
            m_ops += int((nnz - 1).sum()) + tree.size - 1
            d_ops += tree.size * (2 * length - 1) + tree.size - 1
            n += 1
        hanner_ops.append(h_ops)
        matched_ops.append(m_ops)
        dense_ops.append(d_ops)
        groups.append(n)
    hydra_groups = budget // hydra_k
    hydra_group_ops = hydra_k * (2 * length - 1) + 2 * (hydra_k - 1)
    hydra_block = hydra_groups * hydra_group_ops
    h, m, dn = np.mean(hanner_ops), np.mean(matched_ops), np.mean(dense_ops)
    mult = np.mean(sizes) * length * np.mean(groups)
    rows = [
        (
            "Hydra (Gaussian)",
            f"{hydra_k}",
            f"{hydra_group_ops}",
            f"{hydra_groups}",
            f"{hydra_block:,}",
            f"{hydra_groups * hydra_k * length:,}",
        ),
        (
            "Matched control, as timed (dense)",
            f"{np.mean(sizes):.1f}",
            f"{dn / np.mean(groups):.1f}",
            f"{np.mean(groups):.1f}",
            f"{dn:,.0f}",
            f"{mult:,.0f}",
        ),
        (
            "Matched control, sparse (not timed)",
            f"{np.mean(sizes):.1f}",
            f"{m / np.mean(groups):.1f}",
            f"{np.mean(groups):.1f}",
            f"{m:,.0f}",
            "0",
        ),
        (
            "Hanner-Hydra (recursion)",
            f"{np.mean(sizes):.1f}",
            f"{2 * length - 1}",
            f"{np.mean(groups):.1f}",
            f"{h:,.0f}",
            "0",
        ),
    ]
    lines = [
        r"\begin{tabular}{lrrrrr}",
        r"\toprule",
        r" & Vertices & Operations & Groups & Operations & Multipli- \\",
        r" & per group & per group & per block & per block & cations \\",
        r"\midrule",
        *(" & ".join(r) + r" \\" for r in rows),
        r"\midrule",
        rf"\multicolumn{{6}}{{l}}{{Ratios per block: Hydra / Hanner {hydra_block / h:.1f}$\times$, "
        rf"dense control / Hanner {dn / h:.1f}$\times$, sparse control / Hanner "
        rf"{m / h:.1f}$\times$}} \\",
        rf"\multicolumn{{6}}{{l}}{{({n_blocks:,} sampled blocks, seed {seed})}} \\",
        r"\bottomrule",
        r"\end{tabular}",
        "",
    ]
    write("operations", "\n".join(lines))


def figures(bench: Path) -> None:
    out = PAPER / "figures"
    out.mkdir(exist_ok=True)
    for src in sorted((bench / "secondary").glob("cd_*.pdf")):
        shutil.copyfile(src, out / src.name)
        print(f"-> {(out / src.name).relative_to(ROOT)}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tag", default="m2")
    parser.add_argument("--timing-tag", default="endpoint")
    parser.add_argument("--memory-tag", default="endpoint")
    args = parser.parse_args()
    bench = RESULTS_ROOT / args.tag
    primary(bench)
    subsets(bench)
    timing(ROOT / "results" / "timing" / args.timing_tag / "summary.csv")
    memory(ROOT / "results" / "memory" / args.memory_tag / "memory.csv")
    wilcoxon(bench)
    metrics(bench)
    published(bench)
    ablations(bench)
    operations()
    figures(bench)


if __name__ == "__main__":
    main()
